const num = (v: { toString(): string }) => String(Number(v.toString()));

async function main() {
  const version = await prisma.linkSetVersion.findFirst({
    where: { isCurrent: true },
    select: { code: true },
  });
  const laws = await prisma.law.findMany({
    where: { deletedAt: null },
    orderBy: [{ displayOrder: "asc" }, { code: "asc" }],
    select: {
      code: true,
      nameJa: true,
      nameOriginal: true,
      country: { select: { code: true } },
      categories: {
        where: { deletedAt: null },
        orderBy: { displayOrder: "asc" },
        select: {
          code: true,
          nameJa: true,
          nameOriginal: true,
          judged: true,
          thresholdBasis: true,
          aggregation: true,
          metalEtc: true,
          thresholdLower: true,
          lowerBound: true,
          effectiveFrom: true,
          effectiveTo: true,
          classes: {
            where: { deletedAt: null },
            select: {
              statutorySubstances: {
                where: { deletedAt: null },
                select: {
                  thresholdLower: true,
                  applicableCondition: true,
                  metalEtc: true,
                  aggregation: true,
                },
              },
            },
          },
        },
      },
    },
  });
  const nCats = laws.reduce((n, l) => n + l.categories.length, 0);
  const anyAggregated = laws.some((l) =>
    l.categories.some(
      (c) =>
        c.aggregation !== "NONE" ||
        c.classes.some((k) => k.statutorySubstances.some((s) => s.aggregation !== "NONE")),
    ),
  );

  const out: string[] = [];
  const w = (s = "") => out.push(s);
  const today = new Date().toISOString().slice(0, 10);
  w("# 法規制の内容と該非判定の方法");
  w();
  w(
    `${today} 作成（\`scripts/build-regulation-doc.ts\` で作り直せる）。**このシステムに入っている ${laws.length} の法規制・${nCats} の規制区分**について、規制の中身と、製品の該非をどう判定しているかをまとめたもの。`,
  );
  w(
    "判定の仕組みそのものは `docs/judgment-engine.md`、データの作りかたは `docs/法規制データの作り方.md`。",
  );
  w(
    `数値・件数はこのスクリプトを流した環境の DB（法規制バージョン ${version?.code ?? "未設定"}）からの写し。区分の設定を変えたら流し直すこと。「規制の内容」はスクリプトの LAW に手で書いてある。`,
  );
  w();
  w("## 1. 判定のしくみ（全法規制に共通）");
  w();
  w("| 何を | どう決めているか |");
  w("| --- | --- |");
  w(
    "| 判定の単位 | **製品 × 規制区分**。結果（該当／非該当・要確認）は区分ごとに 1 つ保存する。区分の中の**法文物質名ごと**に「当たったか」を持ち、区分の該当は「当たった法文物質名が 1 つでもあるか」で決まる |",
  );
  w(
    "| 見る組成 | 製品の組成を末端まで展開し、CAS ごとに含有率（重量%）を合計したもの。中身の分からない原材料が残れば要確認 |",
  );
  w(
    "| 当たる CAS | 現在の法規制バージョンで、その法文物質名に結び付いている CAS（データソースを問わず全部。非該当で確定させたリンクは除く） |",
  );
  w(
    "| 閾値 | **法文物質名に閾値があればそれを、無ければ区分の閾値を使う。**下限（以上／超）と上限（以下／未満）を持つ。下限 0% 超＝「含めば該当」 |",
  );
  w(
    "| まとめかた | 区分または法文物質名ごとに 3 通り。**まとめない**（CAS ごとに閾値と比べる）／**足す**（複数 CAS の含有率を合計して比べる）／**元素換算**（金属換算係数でその元素の量に直して合計） |",
  );
  w(
    "| 金属換算 | 換算先の元素が決まっている法文物質名は、CAS ごとの換算係数（金属換算係数の表）で元素量に直す。係数が無い CAS は 0 として数え、要確認にする |",
  );
  w(
    "| 適用条件 | 濃度以外の条件（用途・形状・容器・「可能性がある」など）が法文物質名に書いてあれば、**当たったときは必ず要確認**。条件を満たすかは人にしか分からない。濃度が閾値未満でも、条件付きの除外は該当に倒して要確認 |",
  );
  w(
    "| 閾値未設定 | 閾値を入れられなかった法文物質名（印がある）に当たる物質が入っていれば、該当として要確認 |",
  );
  w(
    "| 条件つきの結び付き | 外部データベースが「法律の名称の条件に合致すること」と但し書きを付けた CAS で当たれば警告。要確認にするかはシステム設定 |",
  );
  w(
    "| 均質材料あたりの閾値 | RoHS のように濃度が均質材料あたりの区分は、製品全体の組成では言い切れないので**当たっても当たらなくても要確認** |",
  );
  w(
    "| 適用開始日・終了日 | 区分と法文物質名が持つ。判定対象日を指定した判定では、その日に効いているものだけを使う。保存する判定（対象日なし）では施行前のものも当たり、「施行前」の印だけ付く |",
  );
  w(
    "| 「判定に使う」印 | 外した区分は判定もスコアも対象外（VOC から除かれる物質、水質の生活環境項目、IARC） |",
  );
  w("| 判断できないとき | **該当に倒す**。見落とすより余分に拾うほうが安全 |");
  w(
    "| 人の判断 | 「確認」「該当に変更」「非該当に変更」は**区分ごと**に記録する。前提（当たった法文物質名と CAS の組）が同じあいだは判定し直しても引き継ぎ、変わったら外して要確認にする |",
  );
  w(
    "| スコアとランク | 区分に付けた点数の合計が物質のスコア。スコアを段に読み替えたものがランク（対応表はシステム設定）。**製品の該非とは無関係**。判定の表では法文物質名の行にランクを出し、スコアは浮かせて見せる |",
  );
  w();
  w("## 2. 「区分で決まる」か「法文物質名ごとに決まる」か");
  w();
  w(
    anyAggregated
      ? "区分単位で合算する区分（型 E）以外は、該非は**法文物質名（または CAS）ごと**に決まり、区分の該当はその積み上げでしかない。"
      : `いま入っている ${nCats} 区分は**すべて「まとめない」**（区分単位で合算する区分は無い）。つまり該非は必ず**法文物質名（または CAS）ごと**に決まり、区分の該当はその積み上げでしかない。`,
  );
  w("違いがあるのは**閾値がどこに書いてあるか**で、次の 4 つに分かれる。");
  w();
  w("| 型 | 閾値 | 例 | 画面での見かた |");
  w("| --- | --- | --- | --- |");
  w(
    "| A. 区分で一律 | 区分の閾値をそのまま使う（法文物質名の閾値は区分と同じ値） | 化管法 第1種 1%、有機則 5% 超 | 区分の行の該当＝どれかの法文物質名が閾値を超えた |",
  );
  w(
    "| B. 法文物質名ごと | 法文物質名の閾値がそれぞれ違う（裾切値・除外濃度） | 安衛法 表示・通知、毒劇法、K-REACH、韓国 化学物質管理法 | **該非は法文物質名ごとに決まる。**区分の行はその積み上げ。当たった法文物質名の行に重量%が出る |",
  );
  w(
    "| C. 裾切値なし | 含有していれば該当 | 化審法、大防法、水濁法、中国の目録、条約 | 区分の行の該当＝その物質が入っている |",
  );
  w(
    "| D. 濃度以外で決まる | 用途・製品の種類・均質材料で決まる。濃度だけでは言い切れない | RoHS、K-REACH 制限物質、POPs 附属書A、水俣条約、REACH 附属書XVII | 当たれば要確認。条件は適用条件・備考に書いてあり、人が条文で確かめる |",
  );
  w();
  w(
    "**画面の見かたについて（2026-09-15 の指摘）:** 区分の行に該当／非該当が出るのは、B 型の区分では「その区分のどれかの法文物質名に当たった」という意味でしかない。",
  );
  w(
    "法文物質名ごとの該非は、区分の行を開いた中身（当たった法文物質名の行）に出る。人の判断（確認・変更）は区分ごとにしか付けられないので、",
  );
  w(
    "B 型の区分で「この法文物質名は非該当」と判断したいときの置き場所が無い。この扱いは未決（区分の行の該非をやめて法文物質名の行に付けるか、判断を法文物質名ごとに持つか）。",
  );
  w();
  w("## 3. 法規制ごとの内容と判定");
  w();
  w(
    "表の読みかた: **判定**＝「判定に使う」印。**閾値**＝区分の閾値（下限）。**物質ごとの閾値**＝その区分の法文物質名に入っている閾値の種類。**件数**＝法文物質名の数。**条件**＝適用条件が入っている法文物質名の数（当たると要確認）。**金属換算**＝換算先の元素が入っている法文物質名の数。**型**＝§2 の型。",
  );
  w();

  const byCountry = new Map<string, typeof laws>();
  for (const l of laws) {
    const list = byCountry.get(l.country.code) ?? [];
    list.push(l);
    byCountry.set(l.country.code, list);
  }
  const countries = [
    ...ORDER.filter((c) => byCountry.has(c)),
    ...[...byCountry.keys()].filter((c) => !ORDER.includes(c)),
  ];
  const noCategory: typeof laws = [];
  for (const cc of countries) {
    const list = byCountry.get(cc)!;
    if (list.every((l) => l.categories.length === 0)) {
      noCategory.push(...list);
      continue;
    }
    w(`### ${COUNTRY[cc] ?? cc}`);
    w();
    for (const l of list) {
      if (l.categories.length === 0) {
        noCategory.push(l);
        continue;
      }
      const info = LAW[l.code];
      w(`#### ${info ? info[0] : (l.nameJa ?? l.nameOriginal)}（${l.code}）`);
      w();
      if (info) {
        w(info[1]);
        w();
      }
      w(
        "| 区分 | 規制の内容 | 判定 | 閾値（区分） | 物質ごとの閾値 | 件数 | 条件 | 金属換算 | 型 | 備考 |",
      );
      w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
      for (const c of l.categories) {
        const subs = c.classes.flatMap((k) => k.statutorySubstances);
        const vals = [...new Set(subs.map((s) => Number(s.thresholdLower.toString())))].sort(
          (a, b) => a - b,
        );
        const lower = num(c.thresholdLower);
        const thr =
          lower === "0" && c.lowerBound === "EXCLUSIVE"
            ? "含めば該当"
            : `${lower}% ${c.lowerBound === "INCLUSIVE" ? "以上" : "超"}`;
        const subthr = vals.length <= 1 ? "区分と同じ" : `物質ごと（${vals.join("・")}%）`;
        const conds = subs.filter((s) => s.applicableCondition).length;
        const metal = subs.filter((s) => s.metalEtc).length + (c.metalEtc ? 1 : 0);
        let typ: string;
        if (!c.judged) typ = "—";
        else if (c.aggregation !== "NONE") typ = "E（区分で合算）";
        else if (c.thresholdBasis === "HOMOGENEOUS_MATERIAL") typ = "D（均質材料）";
        else if (vals.length > 1) typ = "B";
        else if (thr === "含めば該当") typ = "C";
        else typ = "A";
        if (conds > 0 && /^[ABC]$/.test(typ)) typ += "／D（条件あり）";
        const note: string[] = [];
        if (c.thresholdBasis === "HOMOGENEOUS_MATERIAL")
          note.push("閾値は均質材料あたり。当たっても当たらなくても要確認");
        if (c.effectiveFrom || c.effectiveTo)
          note.push(
            `適用 ${c.effectiveFrom ? c.effectiveFrom.toISOString().slice(0, 10) : ""}〜${c.effectiveTo ? c.effectiveTo.toISOString().slice(0, 10) : ""}`,
          );
        if (c.classes.length > 1) note.push(`分類 ${c.classes.length} 個`);
        w(
          `| ${esc(c.nameJa ?? c.nameOriginal)}（${c.code}） | ${esc(info?.[2][c.code] ?? "")} | ${c.judged ? "使う" : "**使わない**"} | ${thr} | ${subthr} | ${subs.length} | ${conds || ""} | ${metal || ""} | ${typ} | ${esc(note.join("。"))} |`,
        );
      }
      w();
    }
  }
  if (noCategory.length > 0) {
    w("### 区分を持たないもの（判定しない）");
    w();
    w("| 法規制 | 扱い |");
    w("| --- | --- |");
    for (const l of noCategory)
      w(
        `| ${esc(l.nameJa ?? l.nameOriginal)}（${l.code}） | 区分と物質を入れていないので判定しない（保留事項） |`,
      );
    w();
  }
  w("## 4. まだ判定で見ていないもの（人が確かめること）");
  w();
  w(
    "- **用途ごとの適用除外**（RoHS 附属書III・IV、K-REACH 制限物質、POPs 附属書A、REACH 附属書XVII の条件）。当たれば該当として拾い、除外に当たるかは条文で確かめる",
  );
  w("- **製品の種類で決まるもの**（水俣条約の水銀添加製品、RoHS の対象機器かどうか）");
  w(
    "- **業務にかかる規制**（安衛法の皮膚等障害化学物質等・鉛則・がん原性物質の記録）。含有だけで義務は生じない",
  );
  w(
    "- **均質材料あたりの濃度**（RoHS・韓国 RoHS）。製品全体の組成では薄まる。均質材料そのものを原材料として登録して判定すれば見られる",
  );
  w(
    "- **de minimis・微量混入の限度**（TRI の 1%/0.1%、EU POPs の非意図的混入限度、Prop65 の安全域）。区分に入れていないので、含有していれば該当として出る",
  );
  w(
    "- **有機溶剤の数えかた**（有機則の含有率は混合物中の有機溶剤の合計で見る決まり。いまは CAS ごと）。保留事項に記載",
  );
  w();

  writeFileSync(OUT, out.join("\n") + "\n", "utf8");
  console.warn(`書きました: ${OUT}（${laws.length} 法規制・${nCats} 区分）`);
  const missing = laws.flatMap((l) =>
    l.categories.filter((c) => !LAW[l.code]?.[2][c.code]).map((c) => `${l.code}/${c.code}`),
  );
  if (missing.length > 0) console.warn(`「規制の内容」が書いていない区分: ${missing.join(", ")}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
