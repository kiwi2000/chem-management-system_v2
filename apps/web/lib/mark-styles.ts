/**
 * 判定の印の色。**2種類しかない。**同じ赤にしていたころは、
 * 「片付けるべきもの」と「気に留めておくもの」が同じ重さに見えていた。
 *
 * 色だけに頼らない。**印（? と 三角）で既に区別が付いており**、
 * 色はその上乗せ。色が見分けにくい人にも印で伝わる。
 */

/**
 * 要確認。**判定が変わるかもしれない、正しくないかもしれない。**
 * 答えが出ていないので、いちばん強い色を使う
 */
export const REVIEW_CLASS = "text-destructive";

/**
 * 含有率不足による非該当。**答えは出ている**（いまは非該当）。
 * 配合が変われば当たるという予告なので、赤より一段弱いオレンジにする。
 *
 * 暗い配色では沈むので、そちらでは明るいほうへ振る
 */
export const NEAR_MISS_CLASS = "text-orange-600 dark:text-orange-400";

/**
 * 該当した法文物質名。
 *
 * **色は結果を表す。**「どのデータソースが勝ったか」を色にすると、
 * 含有率不足で当たっていない行まで色が付き、矛盾して見える
 * （採用されたのに非該当、という行ができる）。勝ち負けは**太字**で示す。
 *
 * **赤は使わない。**赤は「要確認」に取ってある
 */
export const HIT_CLASS = "text-blue-700 dark:text-blue-400";

/** 採用されなかったもの。**薄くしない。**載っている事実は同じなので、黒のまま置く */
export const NOT_ADOPTED_CLASS = "text-foreground";
