import { List, Note, P, PageHead, Section, SpecTable, Sub, T } from "../_parts";
import { SpecPager } from "../spec-pager";

/**
 * インベントリの扱い。
 *
 * 読み手は一般の利用者。**何のためのものか → どこを触ると何が変わるか**の順に書く。
 * 判定には使わないこと、番号の出どころがここ1か所であることを先に伝える。
 */
export default function ManualInventoriesPage() {
  return (
    <>
      <PageHead
        title="インベントリを扱う"
        lead="各国が持つ「既存化学物質の目録」です。物質の詳細に出る化審法番号・EC番号・TSCAなどは、すべてここから引いています。左のメニューの「法規制」の中にあります。"
      />

      <Section title="何のためのものか">
        <P>
          インベントリが持っているのは、<T>CAS番号と、その国が振っている番号の対応</T>
          だけです。12か国ぶん、あわせて約95万行あります。
        </P>
        <P>
          <T>判定には使いません。</T>
          「載っているかどうか」は法規制の該当・非該当とは別のことなので、
          製品の法規制判定には出てきません。物質に番号を出すためのものです。
        </P>
      </Section>

      <Section title="一覧で決めること">
        <P>一覧には登録されているインベントリが並びます。直せるのは次の4つです。</P>
        <SpecTable
          head={["欄", "何を決めるか"]}
          rows={[
            ["名称（日本語 / 英語）", "画面に出す名前"],
            ["番号としての呼び名", "物質の画面での見出し（例: 化審法番号）"],
            ["番号として出す", "物質の画面に出すかどうか"],
            ["並び", "物質の画面に出す順。小さいほうが上"],
          ]}
        />
        <P>
          行の右端の<T>鉛筆</T>を押すと、その行の中で直せます。 直したら上の<T>「保存」</T>
          を押してください。
        </P>
        <Note title="出すのをやめても呼び名は残ります">
          <T>「番号として出す」を外すだけ</T>で画面から消えます。呼び名は残るので、
          また出したくなったときに付け直す必要はありません。
          呼び名が空のまま「出す」にはできません（見出しの無い番号が並んでしまうため）。
        </Note>
        <Note title="足したり消したりはできません">
          インベントリそのもの（ENCS・EINECS など）は、取り込みのときに作られます。
          画面から作ると次の取り込みと結び付かなくなるので、
          <T>直せるのは上の4つだけ</T>にしてあります。
        </Note>
      </Section>

      <Section title="該当物質を見る">
        <P>
          一覧の<T>コード</T>を押すと、そのインベントリの該当物質が出ます。
          CAS番号と値の組が並びます。
        </P>
        <SpecTable
          head={["列", "何が出るか"]}
          rows={[
            ["CAS番号", "その行のCAS番号"],
            ["値", "番号（例: (5)-3714）。番号を持たない目録では「該当」のような文字"],
            ["採用", "同じCASが複数のデータソースにあるとき、採られている行に○が付きます"],
            ["登録されている物質", "そのCASの物質。まだ登録していなければ空欄"],
          ]}
        />
        <P>
          <T>「登録されている物質」が空欄でも問題ありません。</T>
          インベントリには、こちらの物質マスタに無いCASも載っているのがふつうです。
        </P>
        <P>
          件数が多いので、上の<T>「フィルター」</T>でCAS番号や値から絞り込んでください。
        </P>
      </Section>

      <Section title="バージョンとデータソース">
        <P>
          インベントリの該当物質は、<T>法規制の対象CASとまったく同じ仕組み</T>で管理しています。
        </P>
        <SpecTable
          head={["持ちもの", "意味"]}
          rows={[
            ["バージョン", "いつ時点の目録か。判定の跡と揃えるために持ちます"],
            ["データソース", "どこから取ったか。同じ目録を別のところから取れます"],
          ]}
        />
        <P>
          表の上に<T>「バージョン」と「データソース」のプルダウン</T>があります。
          <T>この2つの組み合わせを1つだけ</T>見る作りです。
          混ぜて出すと、同じCASが何行も並んでどれが効いているのか読めなくなるためです。
        </P>
        <P>
          はじめは<T>現在のバージョン</T>と、そのバージョンで
          <T>優先度がいちばん高いデータソース</T>が選ばれています。 データソースの選択肢は
          <T>選んだバージョンに並んでいるものだけ</T>が出ます。
          法規制の対象CASの画面も、同じ場所に同じ順で並んでいます。
        </P>
        <Sub title="同じCASが2つ以上あるとき">
          <P>
            <T>優先度がいちばん高いデータソースの行だけが採られます。</T>
            優先度はバージョンごとに決まっていて、<T>「外部データベース」</T>
            の画面で並べ替えられます。
          </P>
          <P>
            <T>「採用」の欄</T>を見てください。いま見ているデータソースの行が採られていれば○、
            他のデータソースに優先度の高い行があれば空欄です。
            <T>データソースを切り替えれば、そちらの行も見られます。</T>
          </P>
        </Sub>
      </Section>

      <Section title="行を直す・足す">
        <P>
          法規制編集の権限があれば、行を足したり直したり消したりできます。
          <T>足した行は、いま選んでいるバージョンとデータソースに入ります。</T>
          直すときも同じです。
        </P>
        <List
          items={[
            <>
              <T>足す</T>… 上の「＋」を押すと、いちばん上に空の行が出ます。CAS番号と値を入れて
              「保存」を押してください（データソースは表の上で選んだものになります）
            </>,
            <>
              <T>直す</T>… 行の右端の鉛筆を押します
            </>,
            <>
              <T>消す</T>… 左の四角で選んでから、ごみ箱を押します
            </>,
          ]}
        />
        <Note title="消したものは戻せません">
          インベントリの行は<T>本当に消えます。</T>
          「載っていない」ことに意味がある表なので、消したものを残しておくと
          「載っているが無効」なのか「載っていない」のかが区別できなくなるためです。
          だれがいつ消したかはアクセス記録に残ります。
        </Note>
        <Note title="取り込み直すと上書きされます">
          手で足した行も、次に同じデータソースから取り込むと
          <T>入れ替えの対象になります。</T>
          長く残したいものは、取り込みの側に反映してもらってください。
        </Note>
      </Section>

      <Section title="物質の画面での見えかた">
        <P>
          物質の詳細を開くと、<T>「各種番号」</T>として並びます。
          見出しはインベントリに付けた呼び名、順は「並び」の順です。
        </P>
        <P>出てこないときは、次の3つを順に確かめてください。</P>
        <List
          items={[
            <>
              その物質に<T>CAS番号が入っているか</T>（入っていないと番号をたどれません）
            </>,
            <>
              そのインベントリが<T>「番号として出す」</T>になっているか
            </>,
            <>
              そのインベントリの該当物質に<T>そのCASがあるか</T>（フィルターで探せます）
            </>,
          ]}
        />
      </Section>

      <SpecPager current="/spec/inventories" />
    </>
  );
}
