/**
 * ブロックの幅。
 *
 * **入れ子にしない。**「横並び」という入れものを作ると、
 * その中にまた入れられることになり、並べ替えも中と外で別々に要る。
 * かわりに1つずつ幅を持たせ、**幅の合計が1に収まるあいだ横に続ける**。
 * 並びは上から下のままなので、これまでの並べ替えがそのまま使える。
 */
/**
 * 昔の書き方。**読むだけ。**新しく作るものは％で持つ。
 * 既に保存されているテンプレートがこの形なので、捨てられない
 */
const LEGACY_WIDTH: Record<string, number> = {
  full: 100,
  twoThirds: 66,
  half: 50,
  third: 33,
};

/**
 * ブロックの幅。
 *
 *   数（5〜100） … その割合。100 は全幅
 *   "auto"       … 均等。**同じ行の均等どうしで、残りを等分する**
 *   昔の名前     … 読むためだけに残してある
 */
export type BlockWidth = number | "auto" | "full" | "twoThirds" | "half" | "third";

/** 選べる％。細かすぎると選ぶのが手間なので、よく使うものだけ並べる */
export const WIDTH_PERCENTS = [100, 75, 66, 60, 50, 40, 33, 25, 20] as const;

/** 打ち込める％の範囲。5未満は文字が入らず、幅として意味がない */
export const WIDTH_MIN = 5;
export const WIDTH_MAX = 100;

/** 幅を％の数にする。均等は数が決まらないので null */
export function widthPercent(w: BlockWidth | undefined): number | null {
  if (w === undefined) return 100;
  if (w === "auto") return null;
  if (typeof w === "number") return w;
  return LEGACY_WIDTH[w] ?? 100;
}

/** 幅として通る値か（保存する前に確かめる） */
export function isBlockWidth(v: unknown): v is BlockWidth {
  if (v === "auto") return true;
  if (typeof v === "string") return v in LEGACY_WIDTH;
  return typeof v === "number" && Number.isInteger(v) && v >= WIDTH_MIN && v <= WIDTH_MAX;
}

/** 行を絞る条件。値はどの列も文字として扱う */
export const TABLE_FILTER_OPS = [
  "contains",
  "notContains",
  "equals",
  "notEquals",
  "empty",
  "notEmpty",
  "matches",
] as const;
export type TableFilterOp = (typeof TABLE_FILTER_OPS)[number];

export interface TableFilter {
  column: string;
  op: TableFilterOp;
  /** `empty` / `notEmpty` では使わない */
  value?: string;
}

/**
 * 値の置き換え。
 * **正規表現で探して、当たったところを差し替える。**
 * 「該当」を「〇」にする、単位を落とす、といった紙面だけの整えに使う
 */
export interface TableReplacement {
  column: string;
  /** 探す形（正規表現） */
  pattern: string;
  /** 置き換える文字。`$1` で括弧の中を差し込める */
  replacement: string;
}

/** 打ち間違いで紙面が壊れないよう、読めない形は当てずに素通りさせる */
export function compileReplacement(r: TableReplacement): RegExp | null {
  if (r.pattern === "") return null;
  try {
    return new RegExp(r.pattern, "g");
  } catch {
    return null;
  }
}

/** その行を出すか */
export function passesFilter(cell: string, f: TableFilter): boolean {
  const v = f.value ?? "";
  switch (f.op) {
    case "contains":
      return cell.includes(v);
    case "notContains":
      return !cell.includes(v);
    case "equals":
      return cell === v;
    case "notEquals":
      return cell !== v;
    case "empty":
      return cell === "";
    case "notEmpty":
      return cell !== "";
    case "matches": {
      if (v === "") return true;
      try {
        return new RegExp(v).test(cell);
      } catch {
        // 読めない形は「絞らない」。打っている途中で行が消えると、直しようがない
        return true;
      }
    }
    default:
      return true;
  }
}

