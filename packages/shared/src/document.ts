/**
 * ドキュメント生成のテンプレート。
 *
 * テンプレートは**システムの中で作る**（Wordファイルは使わない）。
 * 中身はここで決めた形の JSON で、`document_templates.content` に入る。
 *
 * ## なぜ Word ではないのか
 *
 * Word に差し込む形だと、`{product.cod}` のような打ち間違いを
 * 登録のときに検査する仕組みが別に要る。
 * **項目を一覧から選ばせれば、無い項目は書きようがない。**
 *
 * ## 出す形に引きずられないこと
 *
 * ここに置くのは「何を、どの順で出すか」だけ。
 * HTML にするのか .docx にするのかは、出す側（レンダラ）が決める。
 * **JSON に出力形式のことを書かない。**書くと、出し先が増えるたびに
 * 作ったテンプレートを作り直すことになる。
 */

